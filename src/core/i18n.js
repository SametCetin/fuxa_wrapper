  let current = 'tr';

  /** Sistem dili (ör. "tr-TR", "en-US") → desteklenen dil; Türkçe değilse İngilizce. */
  function resolve(locale) {
    const l = String(locale || '').toLowerCase().split(/[-_]/)[0];
    return LANGUAGES.includes(l) ? l : 'en';
  }

  function setLanguage(lang) {
    current = LANGUAGES.includes(lang) ? lang : 'en';
    return current;
  }

  function getLanguage() {
    return current;
  }

  function t(key, vars) {
    const s = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
    return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;
  }

  /** Bir metnin tüm dillerdeki hali (ör. yeni proje adı "Adsız"/"Untitled" tanınsın). */
  function all(key) {
    return LANGUAGES.map((l) => STRINGS[l][key]).filter(Boolean);
  }

  /** Tarih/saat biçimi için yerel ayar. */
  function locale() {
    return current === 'tr' ? 'tr-TR' : 'en-US';
  }

  return { LANGUAGES, NATIVE_NAMES, STRINGS, resolve, setLanguage, getLanguage, t, all, locale };
